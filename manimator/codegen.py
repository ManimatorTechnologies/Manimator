# Web mode: a FILE value is just the name of an uploaded file. Generated code needs a path, so the
# caller says where the uploads live ("assets" for exported code, an absolute folder for rendering).
_ASSET_ROOT: ContextVar[str | None] = ContextVar("manimator_asset_root", default=None)
ASSET_NAME = re.compile(r"^[A-Za-z0-9._-]{1,80}$")


@contextmanager
def asset_root(root):
    token = _ASSET_ROOT.set(None if root is None else str(root))
    try:
        yield
    finally:
        _ASSET_ROOT.reset(token)


