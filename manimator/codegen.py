# ---------------------------------------------------------------------- values


def num(v: float) -> str:
    v = round(float(v), 4)
    if v == int(v):
        return str(int(v))
    return repr(v)


def py_str(s: str) -> str:
    """String literal, preferring r"..." for LaTeX so backslashes stay readable (never with a control character in
    it, such as a carriage return: a raw string can only write it as itself, which breaks the line)."""
    if "\\" in s and '"' not in s and not s.endswith("\\") and all(c == "\t" or " " <= c != "\x7f" for c in s):
        return f'r"{s}"'
    r = repr(s)
    if r.startswith("'") and '"' not in s:
        r = '"' + r[1:-1].replace("\\'", "'") + '"'
    return r


def num_node(v) -> Lit:
    return number(num(v))


def str_node(s: str) -> Lit:
    return Lit(py_str(s), s)


def vector_node(v) -> Lit:
    x, y = round(float(v[0]), 4), round(float(v[1]), 4)
    parts = []
    for amount, pos, neg in ((x, "RIGHT", "LEFT"), (y, "UP", "DOWN")):
        if amount == 0:
            continue
        name = pos if amount > 0 else neg
        a = abs(amount)
        parts.append(name if a == 1 else f"{num(a)} * {name}")
    return Lit(" + ".join(parts) if parts else "ORIGIN", [x + 0.0, y + 0.0, 0.0])


def vector_code(v) -> str:
    return vector_node(v).code


def point_node(v) -> Seq:
    z = num_node(v[2]) if len(v) > 2 else Lit("0", 0)
    return Seq((num_node(v[0]), num_node(v[1]), z))


def point_code(v) -> str:
    return point_node(v).py()


def color_node(c) -> Lit:
    return Lit(color_code(c), normalize(c))


def angle_node(v) -> Lit:
    if float(v) == 0:
        return Lit("0", 0)
    code = num(v)
    return Lit(f"{code} * DEGREES", float(code) * DEGREES)


def direction_node(v) -> Lit:
    if v not in DIRECTION_VECTORS:  # bare identifiers only ever come from allow-lists
        raise ValueError(f"unknown direction {v!r}")
    x, y = DIRECTION_VECTORS[v]
    return Lit(v, [float(x), float(y), 0.0])


def enum_node(p: Param, v) -> Node:
    if v not in {value for value, _label in p.choices}:
        raise ValueError(f"unknown choice {v!r}")
    if not p.raw:
        return Lit(repr(v), v)
    if v.isdigit():  # stretch(dim=0)
        return Lit(v, int(v))
    if v in DIRECTION_VECTORS:  # flip(axis=UP)
        return direction_node(v)
    return Name(v)  # Circumscribe(shape=Rectangle)


def expr_node(text, variables, subst: dict[str, str] | None = None) -> Expr:
    return Expr(compile_expr(text, variables, subst), expr_tree(text, variables))


def file_node(v) -> Node:
    root = _ASSET_ROOT.get()
    if root is None:  # no asset folder (plain code generation): the path as typed
        return Lit(py_str(str(v)), str(v))
    if not ASSET_NAME.match(str(v)) or str(v).startswith("."):  # never anything but a plain file name
        raise ValueError("invalid file name")
    return Asset(py_str(root.rstrip("/\\") + "/" + str(v)), str(v))


def value_node(p: Param, v, names: dict[str, str]) -> Node:
    k = p.kind
    if k == FLOAT:
        return num_node(v)
    if k == INT:
        return Lit(str(int(v)), int(v))
    if k in (STR, TEXT, FONT):
        return str_node(str(v))
    if k == BOOL:
        return Lit("True" if v else "False", bool(v))
    if k == COLOR:
        return color_node(v)
    if k in (POINT, POINT3):
        return point_node(v)
    if k == VECTOR:
        return vector_node(v)
    if k == DIRECTION:
        return direction_node(v)
    if k == ANGLE:
        return angle_node(v)
    if k == ENUM:
        return enum_node(p, v)
    if k == MOBREF:
        if v not in names:
            raise MissingReference(p.title)
        return Ref(v, names[v])
    if k == RANGE:
        return Seq((num_node(v[0]), num_node(v[1]), num_node(v[2])))
    if k == EXPR:
        return expr_node(v, p.variables)
    if k == POINTS:
        return Seq(tuple(point_node(pt) for pt in v))
    if k == NUMBERS:
        return Seq(tuple(num_node(n) for n in v))
    if k == GRID:
        cell = (lambda c: num_node(float(c))) if p.numeric else (lambda c: str_node(str(c)))
        return Seq(tuple(Seq(tuple(cell(c) for c in row)) for row in v))
    if k == FILE:
        return file_node(v)
    if k == MOBREFS:
        return Seq(tuple(Ref(i, names[i]) for i in v if i in names))
    raise ValueError(f"unknown param kind {k}")


def value_code(p: Param, v, names: dict[str, str]) -> str:
    return value_node(p, v, names).py()


def call_nodes(params: tuple[Param, ...], values: dict, names: dict[str, str]):
    """Positional args first, then keyword args that differ from their defaults: (args, kwargs)."""
    pos: list[Node] = []
    kw: list[tuple[str, Node]] = []
    for p in params:
        v = values.get(p.name, p.default)
        if p.positional:
            pos.append(value_node(p, v, names))
            continue
        if v is None and (p.optional or p.kind == MOBREF):
            continue
        if p.when is not None and not p.when(values):
            continue
        if not p.emit_default and v == p.default:
            continue
        if p.emit is not None:
            pair = p.emit(v)
            if pair is not None:
                kw.append(pair)
            continue
        kw.append((p.name, value_node(p, v, names)))
    return tuple(pos), tuple(kw)


def call_args(params: tuple[Param, ...], values: dict, names: dict[str, str]) -> list[str]:
    pos, kw = call_nodes(params, values, names)
    return [a.py() for a in pos] + [f"{k}={v.py()}" for k, v in kw]


# ---------------------------------------------------------------------- objects


class Args:
    """What a spec's `build` function sees: the object's values, as call-tree nodes."""

    def __init__(self, spec, values: dict, names: dict[str, str]):
        self._params = {p.name: p for p in spec.params}
        self._values = values
        self._names = names

    def raw(self, name: str):
        return self._values.get(name, self._params[name].default)

    def code(self, name: str) -> Node:
        """The parameter as a node (a number, a point list, a color name...)."""
        return value_node(self._params[name], self.raw(name), self._names)

    def call(self, cls: str) -> Call:
        """`cls(...)` with every parameter, as a plain spec's call is written (custom objects)."""
        return Call(cls, *call_nodes(tuple(self._params.values()), self._values, self._names))

    def expr(self, name: str, subst: dict[str, str] | None = None) -> Expr:
        p = self._params[name]
        return expr_node(self.raw(name), p.variables, subst)

    def refs(self, name: str) -> tuple[Ref, ...]:
        """The referenced objects (for VGroup(...))."""
        return tuple(Ref(i, self._names[i]) for i in (self.raw(name) or []) if i in self._names)

    num = staticmethod(num_node)
    pt = staticmethod(point_node)
    s = staticmethod(lambda text: str_node(str(text)))


@dataclass
class MobCode:
    mob_id: str
    var: str
    call: Call = field(default_factory=lambda: Call("VMobject"))  # the constructor
    post_calls: list[Call] = field(default_factory=list)  # run after construction, on the object
    deps: set[str] = field(default_factory=set)  # object ids referenced
    error: str | None = None  # set when code could not be generated

    @property
    def ctor(self) -> str:  # "Circle(radius=1)"
        return self.call.py()

    @property
    def post(self) -> list[str]:
        return [c.py() for c in self.post_calls]

    def lines(self) -> list[str]:
        return [f"{self.var} = {self.ctor}", *self.post]


def _style_calls(on: Ref, item: MobjectItem) -> list[Call]:
    spec = MOBJECTS[item.type]
    st = item.style
    nat = spec.natural
    calls = []

    def differs(key: str) -> bool:
        return key in st and st[key] != nat.get(key)

    if spec.style_kind == SHAPE:
        stroke = []
        if differs("stroke_width"):
            stroke.append(("width", num_node(st["stroke_width"])))
        if differs("stroke_opacity"):
            stroke.append(("opacity", num_node(st["stroke_opacity"])))
        calls.append(Call("set_stroke", (color_node(st["stroke_color"]),), tuple(stroke), on=on))
        fill = (("opacity", num_node(st["fill_opacity"])),) if differs("fill_opacity") else ()
        calls.append(Call("set_fill", (color_node(st["fill_color"]),), fill, on=on))
    elif spec.style_kind == LINE:
        calls.append(Call("set_color", (color_node(st["color"]),), on=on))
        extra = []
        if differs("stroke_width"):
            extra.append(("width", num_node(st["stroke_width"])))
        if differs("stroke_opacity"):
            extra.append(("opacity", num_node(st["stroke_opacity"])))
        if extra:
            calls.append(Call("set_stroke", (), tuple(extra), on=on))
    elif spec.style_kind == TEXTISH:
        if st.get("color"):
            calls.append(Call("set_color", (color_node(st["color"]),), on=on))
        if st.get("opacity", 1.0) != 1.0:
            calls.append(Call("set_opacity", (num_node(st["opacity"]),), on=on))
    elif spec.style_kind == COORDS:
        if st.get("color"):
            calls.append(Call("set_color", (color_node(st["color"]),), on=on))
    elif spec.style_kind == OPACITY:
        if st.get("opacity", 1.0) != 1.0:
            calls.append(Call("set_opacity", (num_node(st["opacity"]),), on=on))
    return calls


def method_node(call: MethodCall, names: dict[str, str], on: Node | None = None) -> Call:
    spec = METHODS.get(call.method)
    if spec is None:
        raise ValueError(f"unknown method {call.method!r}")
    args, kwargs = call_nodes(spec.params, call.args, names)
    return Call(spec.key, args, kwargs, on=on)


def method_code(call: MethodCall, names: dict[str, str]) -> str:
    return method_node(call, names).py()


def mobject_code(item: MobjectItem, names: dict[str, str], from_origin: bool = False) -> MobCode:
    """`from_origin`: a vector that a LinearTransformationScene carries along. Those are redrawn from the
    origin as the grid moves, so it stays there: no move_to, and turning and scaling happen about the origin."""
    spec = MOBJECTS[item.type]
    var = names[item.id]
    me = Ref(item.id, var)
    code = MobCode(item.id, var, deps=mobject_refs(item))
    try:
        if spec.build is not None:
            code.call = spec.build(Args(spec, item.params, names))
        else:
            args, kwargs = call_nodes(spec.params, item.params, names)
            code.call = Call(item.type, args, kwargs)
        post = _style_calls(me, item)
        about = (("about_point", Lit("ORIGIN", [0.0, 0.0, 0.0])),) if from_origin else ()
        if spec.positioned and not spec.point_params and not from_origin:
            where = [*item.position, item.z] if spec.three_d else item.position
            post.append(Call("move_to", (point_node(where),), on=me))
        if item.rotation:
            post.append(Call("rotate", (angle_node(item.rotation),), about, on=me))
        if item.scale != 1:
            post.append(Call("scale", (num_node(item.scale),), about, on=me))
        if item.z_index:
            post.append(Call("set_z_index", (Lit(str(int(item.z_index)), int(item.z_index)),), on=me))
    except MissingReference as e:
        code.call = Call("VMobject")
        code.error = f"'{e}' is not set"
        return code
    except Unavailable as e:  # a custom object whose package is gone
        code.call = Call("VMobject")
        code.error = str(e)
        return code
    except BAD_DATA as e:  # hand-edited project file
        code.call = Call("VMobject")
        code.error = f"invalid value ({e})"
        return code
    for call in item.methods:
        try:
            post.append(method_node(call, names, on=me))
        except MissingReference as e:
            code.error = f"{METHODS[call.method].label}: '{e}' is not set"
        except BAD_DATA as e:
            code.error = f"{METHODS[call.method].label}: invalid value ({e})"
    code.post_calls = post
    return code


def build_order(scene: Scene) -> list[MobjectItem]:
    """Objects in layer order, except that referenced objects are built first."""
    remaining = list(scene.mobjects)
    ids = {m.id for m in remaining}
    done: set[str] = set()
    order: list[MobjectItem] = []
    while remaining:
        for m in remaining:
            if (mobject_refs(m) & ids) <= done:
                break
        else:  # a cycle; the UI prevents these, so just keep going in layer order
            m = remaining[0]
        remaining.remove(m)
        done.add(m.id)
        order.append(m)
    return order


def scene_names(scene: Scene) -> dict[str, str]:
    return {m.id: safe_identifier(m.name) for m in scene.mobjects}


def scene_objects(scene: Scene) -> tuple[list[MobCode], dict[str, str]]:
    names = scene_names(scene)
    origin = origin_vectors(scene)
    return [mobject_code(m, names, m.id in origin) for m in build_order(scene)], names


def origin_vectors(scene: Scene) -> set[str]:
    """Vectors a LinearTransformationScene moves with its grid (they start at the origin)."""
    if scene.kind != LINEAR:
        return set()
    return {m.id for m in top_level(scene) if m.type == "Vector" and transform_role(m) == MOVING_VECTOR}


# ---------------------------------------------------------------------- animations


def animation_node(anim: AnimationItem, names: dict[str, str]) -> Node:
    if anim.target not in names:
        raise MissingReference("Target")
    target = Ref(anim.target, names[anim.target])
    if anim.anim == ANIMATE:
        call = MethodCall(anim.method or "shift", anim.params)
        return Animate(target, (method_node(call, names),))
    spec = ANIMATIONS.get(anim.anim)
    if spec is None:
        raise ValueError(f"unknown animation {anim.anim!r}")
    if spec.blocked:  # a custom animation whose package is gone: the step plays without it
        raise Unavailable(spec.description)
    args, kwargs = call_nodes(spec.params, anim.params, names)
    return Call(spec.call_name or spec.key, (target, *args), kwargs)


def animation_code(anim: AnimationItem, names: dict[str, str]) -> str:
    return animation_node(anim, names).py()


def _join_call(prefix: str, args: list[str], indent: str) -> list[str]:
    return join_call(prefix, args, indent)


def _width(zoom) -> FrameWidth:
    """The camera frame's width for a zoom level (1 = Manim's whole frame)."""
    return FrameWidth(float(zoom), num(zoom))


def _degrees(v) -> Lit:
    return angle_node(v)


def _self_call(path: str, *args: Node, **kwargs: Node) -> Call:
    """A call on the scene or one of its attributes: _self_call("self.camera.frame.save_state")."""
    on, _, name = path.rpartition(".")
    return Call(name, tuple(args), tuple(kwargs.items()), on=SELF if on == "self" else Attr(on))


@dataclass
class ActionCode:
    """What one scene action adds to its step."""

    before: list = field(default_factory=list)  # statements before the step plays
    anims: list = field(default_factory=list)  # animations played along with the step's others
    call: Call | None = None  # a scene method that plays the step (with its own arguments)
    statement: Do | None = None  # a scene method that plays a fixed sequence (alone in its step)
    after: list = field(default_factory=list)  # statements after the step plays


_REGISTER = {TRANSFORMABLE: "self.add_transformable_mobject", FOREGROUND: "self.add_foreground_mobject",
             STATIC: "self.add"}
_CLEAR_NOTE = ("# Scene.play() keeps its own list in self.moving_mobjects, the same attribute\n"
               "# LinearTransformationScene reads; empty it so only the grid's objects move.")


@dataclass
class StepCode:
    """One step of the animation part of construct(): its statements, and how it plays for the browser."""

    statements: list  # Do / Assign / Comment, in order
    play: int | None = None  # index in `statements` of the statement that takes the step's time
    run_time: float = 0.0  # how long the step lasts


class _Walk:
    """Writes the animation part of construct() step by step, remembering what earlier steps changed:
    whether the zoom is on, which 3D camera settings were used, and which objects a LinearTransformationScene
    carries along (objects join its lists when they come on screen and leave them when they go)."""

    def __init__(self, scene: Scene, names: dict[str, str]):
        self.scene = scene
        self.names = names
        self.kind = scene_kind(scene)
        self.zoom_on = scene.kind == ZOOMED and bool(scene_option(scene, "zoom_at_start"))
        self.zoom_activated = self.zoom_on
        self.used = {}  # 3D: move_camera arguments that differ from Manim's defaults at some point
        if self.kind.three_d:
            self.used = {"gamma": _option_value(scene, "gamma") != 0, "zoom": _option_value(scene, "zoom") != 1}
        self.cleared = False
        self.states = screen_states(scene)
        self.roles: dict[str, str] = {}  # LinearTransformationScene: id -> role, for objects in its lists
        if scene.kind == LINEAR:
            self.roles = {i: r for i, r in _lts_roles(scene).items() if i in self.states[0] and r != STATIC}

    def ref(self, mob_id: str) -> Ref:
        return Ref(mob_id, self.names[mob_id])

    # ------------------------------------------------------------------ steps
    def step_code(self, index: int, step: Step) -> StepCode:
        if step.kind == WAIT:
            return StepCode([Do(_self_call("self.wait", num_node(step.duration)))], 0, float(num(step.duration)))
        codes: dict[int, ActionCode] = {}
        actions = [i for i, a in enumerate(step.animations) if is_action(a)]
        self.zoom_shown = self.zoom_on  # whether the zoom is visible at some point during this step
        for i in sorted(actions, key=lambda i: ANIMATIONS[step.animations[i].anim].channel != "zoom"):
            try:  # the zoom goes first: lens moves play differently while it is off
                codes[i] = getattr(self, f"_{step.animations[i].anim}")(step.animations[i])
            except BAD_DATA:
                continue
        anims: list[Node] = []
        for i, a in enumerate(step.animations):
            if i in codes:
                anims += codes[i].anims
            elif i not in actions:
                try:
                    anims.append(animation_node(a, self.names))
                except BAD_DATA:
                    continue
        acts = [codes[i] for i in sorted(codes)]
        stmts: list = [s for c in acts for s in c.before]
        kw = [("run_time", num_node(step.run_time))]
        if step.rate_func != "default" and step.rate_func in _RATE_FUNC_NAMES:
            kw.append(("rate_func", Name(step.rate_func)))
        statement = next((c.statement for c in acts if c.statement), None)
        call = next((c.call for c in acts if c.call), None)
        if step.lag_ratio > 0 and len(anims) > 1:
            anims = [Call("LaggedStart", tuple(anims), (("lag_ratio", num_node(step.lag_ratio)),))]
        play = len(stmts)
        run_time = float(num(step.run_time))
        if statement:
            stmts.append(statement)
        elif call:
            kwargs = list(call.kwargs)
            if anims:
                kwargs.append(("added_anims", Seq(tuple(anims))))
            stmts.append(Do(Call(call.name, call.args, tuple(kwargs + kw), on=call.on), wrap=True))
        elif anims:
            stmts.append(Do(_self_call("self.play", *anims, **dict(kw)), wrap=True))
        elif acts:  # e.g. a spinning camera and nothing else
            stmts.append(Do(_self_call("self.wait", num_node(step.run_time))))
        else:
            return StepCode([], None, 0.0)
        stmts += [s for c in acts for s in c.after]
        if self.scene.kind == LINEAR:
            stmts += _call_stmts(self._lts_changes(self.states[index + 1]))
        return StepCode(stmts, play, run_time)

    def step(self, index: int, step: Step) -> list[str]:
        return [line for s in self.step_code(index, step).statements for line in s.lines(INDENT)]

    def _obj(self, anim: AnimationItem, name: str) -> Ref:
        mob_id = anim.params.get(name)
        if mob_id not in self.names:
            raise MissingReference(name)
        return self.ref(mob_id)

    def _num(self, anim: AnimationItem, name: str, lo: float = -1e9, hi: float = 1e9) -> float:
        p = next(p for p in ANIMATIONS[anim.anim].params if p.name == name)
        v = float(anim.params.get(name, p.default))
        if v != v or not lo <= v <= hi:
            raise ValueError(f"{name} out of range")
        return v

    def _point(self, anim: AnimationItem, name: str) -> Node:
        p = next(p for p in ANIMATIONS[anim.anim].params if p.name == name)
        return value_node(p, anim.params.get(name, p.default), self.names)

    # ------------------------------------------------------------------ MovingCameraScene, ZoomedScene
    FRAME = Attr("self.camera.frame")

    def _camera_pan(self, a):
        return ActionCode(anims=[Animate(self.FRAME, (Call("move_to", (self._point(a, "point"),)),))])

    def _camera_focus(self, a):
        zoom = self._num(a, "zoom", 0.01, 1000)
        return ActionCode(anims=[Animate(self.FRAME, (Call("move_to", (self._obj(a, "object"),)),
                                                      Call("set", (), (("width", _width(zoom)),))))])

    def _camera_zoom(self, a):
        zoom = self._num(a, "zoom", 0.01, 1000)
        return ActionCode(anims=[Animate(self.FRAME, (Call("set", (), (("width", _width(zoom)),)),))])

    def _camera_fit(self, a):
        objs = [self.ref(i) for i in a.params.get("objects") or [] if i in self.names]
        if not objs:
            raise MissingReference("Objects")
        margin = float(a.params.get("margin", 1.0))
        extra = (("margin", num_node(margin)),) if margin else ()
        return ActionCode(anims=[Call("auto_zoom", (Seq(tuple(objs)),), extra, on=Attr("self.camera"))])

    def _camera_restore(self, a):
        return ActionCode(anims=[Call("Restore", (self.FRAME,))])

    # ------------------------------------------------------------------ ZoomedScene
    LENS = Attr("self.zoomed_camera.frame")
    DISPLAY = Attr("self.zoomed_display")

    def _zoom_on(self, a):
        code = ActionCode()
        if not self.zoom_on:
            if self.zoom_activated:  # turned off earlier: bring the lens and its display back
                code.before.append(Do(_self_call("self.add_foreground_mobjects", self.LENS, self.DISPLAY)))
            else:
                code.before.append(Do(_self_call("self.activate_zooming")))
            self.zoom_on = self.zoom_activated = self.zoom_shown = True
        if a.params.get("pop_out", True):
            code.anims.append(_self_call("self.get_zoomed_display_pop_out_animation"))
        return code

    def _zoom_off(self, a):
        if not self.zoom_on:
            return ActionCode()
        self.zoom_on = False
        return ActionCode(anims=[Call("FadeOut", (self.DISPLAY,)), Call("FadeOut", (self.LENS,))])

    def _lens(self, change: Call) -> ActionCode:
        if self.zoom_shown:
            return ActionCode(anims=[Animate(self.LENS, (change,))])
        # unseen while the zoom is off
        return ActionCode(before=[Do(Call(change.name, change.args, change.kwargs, on=self.LENS))])

    def _lens_to_object(self, a):
        return self._lens(Call("move_to", (self._obj(a, "object"),)))

    def _lens_to_point(self, a):
        return self._lens(Call("move_to", (self._point(a, "point"),)))

    def _lens_scale(self, a):
        return self._lens(Call("scale", (num_node(self._num(a, "factor", 0.001, 1000)),)))

    # ------------------------------------------------------------------ ThreeDScene, SpecialThreeDScene
    def _camera_move3d(self, a):
        values = {k: self._num(a, k, -36000, 36000) for k in ("phi", "theta", "gamma", "zoom")}
        if not values["zoom"] > 0:
            raise ValueError("zoom must be positive")
        kwargs = [("phi", _degrees(values["phi"])), ("theta", _degrees(values["theta"]))]
        if values["gamma"] != 0 or self.used.get("gamma"):
            kwargs.append(("gamma", _degrees(values["gamma"])))
            self.used["gamma"] = True
        if values["zoom"] != 1 or self.used.get("zoom"):
            kwargs.append(("zoom", num_node(values["zoom"])))
            self.used["zoom"] = True
        return ActionCode(call=Call("move_camera", (), tuple(kwargs), on=SELF))

    def _camera_look_at(self, a):
        return ActionCode(call=Call("move_camera", (), (("frame_center", self._obj(a, "object")),), on=SELF))

    def _camera_look_point(self, a):
        return ActionCode(call=Call("move_camera", (), (("frame_center", self._point(a, "point")),), on=SELF))

    def _camera_spin(self, a):
        rate = self._num(a, "rate", -36000, 36000)
        about = a.params.get("about", "theta")
        if about not in ("theta", "phi", "gamma"):
            raise ValueError("unknown axis")
        if about == "gamma":
            self.used["gamma"] = True
        axis = () if about == "theta" else (("about", str_node(about)),)
        return ActionCode(before=[Do(Call("begin_ambient_camera_rotation", (), (("rate", _degrees(rate)), *axis),
                                          on=SELF))],
                          after=[Do(Call("stop_ambient_camera_rotation", (), axis, on=SELF))])

    def _camera_wobble(self, a):
        rate = self._num(a, "rate", 0.001, 1000)
        kwargs = () if rate == 1 else (("rate", num_node(rate)),)
        return ActionCode(before=[Do(Call("begin_3dillusion_camera_rotation", (), kwargs, on=SELF))],
                          after=[Do(_self_call("self.stop_3dillusion_camera_rotation"))])

    # ------------------------------------------------------------------ LinearTransformationScene
    def _clear(self) -> list:
        stmts = [] if self.cleared else [Comment(_CLEAR_NOTE)]
        self.cleared = True
        return [*stmts, Assign("self.moving_mobjects", Lit("[]", []))]

    def _matrix(self, a) -> Node:
        spec = ANIMATIONS[a.anim]
        spec.check(a.params)
        return value_node(spec.params[0], a.params.get("matrix"), self.names)

    def _apply_matrix(self, a):
        return ActionCode(before=self._clear(), call=Call("apply_matrix", (self._matrix(a),), on=SELF))

    def _apply_inverse(self, a):
        return ActionCode(before=self._clear(), call=Call("apply_inverse", (self._matrix(a),), on=SELF))

    def _apply_function(self, a):
        params = {p.name: p for p in ANIMATIONS[a.anim].params}
        sub = {"x": "p[0]", "y": "p[1]"}
        fx = expr_node(a.params.get("fx", params["fx"].default), params["fx"].variables, sub)
        fy = expr_node(a.params.get("fy", params["fy"].default), params["fy"].variables, sub)
        # With the moving grid, Manim first adds points to its lines so they can bend smoothly.
        method = "apply_nonlinear_transformation" if scene_option(self.scene, "include_foreground_plane") \
            else "apply_function"
        func = Lambda(("p",), Call("np.array", (Seq((fx, fy, Lit("0", 0))),)), (("x", "p", 0), ("y", "p", 1)))
        return ActionCode(before=self._clear(), call=Call(method, (func,), on=SELF))

    def _lts_changes(self, now: set[str]) -> list[tuple[str, list[Ref]]]:
        """Objects that came on screen join the scene's lists; ones that left are taken out of them."""
        roles = _lts_roles(self.scene)
        calls = []
        for mob_id in [m.id for m in self.scene.mobjects if m.id in self.roles and m.id not in now]:
            role = self.roles.pop(mob_id)
            if role == TRANSFORMABLE:
                calls.append(("self.transformable_mobjects.remove", [self.ref(mob_id)]))
            elif role == MOVING_VECTOR:
                calls.append(("self.moving_vectors.remove", [self.ref(mob_id)]))
            # Scene.remove() has already taken a foreground object out of foreground_mobjects
        joining = [m for m in top_level(self.scene)
                   if m.id in now and m.id not in self.roles and roles[m.id] != STATIC]
        calls += _lts_add_calls(joining, roles, self.names)
        self.roles.update({m.id: roles[m.id] for m in joining})
        return calls

    # ------------------------------------------------------------------ VectorScene
    def _vector_to_coords(self, a):
        x, y = (float(v) for v in a.params.get("vector", [2.0, 1.0])[:2])
        kwargs = () if a.params.get("integer_labels", True) else (("integer_labels", Lit("False", False)),)
        vec = Seq((num_node(x), num_node(y)))
        return ActionCode(statement=Do(Call("vector_to_coords", (vec,), kwargs, on=SELF)))


def _option_value(scene: Scene, name: str):
    """A scene setting, checked like any other value (a project file could hold anything); its default if not."""
    kind = scene_kind(scene)
    p = kind.option(name)
    value = scene.options.get(name, p.default) if kind.active(name, scene.options) else p.default
    try:
        value_code(p, value, {})
        if p.kind == FLOAT:
            value = float(value)
            if value != value or not p.min <= value <= p.max:
                raise ValueError
    except BAD_DATA:
        return p.default
    return value


scene_option = _option_value


def _lts_roles(scene: Scene) -> dict[str, str]:
    return {m.id: transform_role(m) for m in scene.mobjects}


def _runs(items: list[MobjectItem], method, names: dict[str, str]) -> list[tuple[str, list[Ref]]]:
    """One call per run of neighbouring objects that use the same method (in layer order)."""
    calls: list[tuple[str, list[Ref]]] = []
    for m in items:
        name = method(m)
        ref = Ref(m.id, names[m.id])
        if calls and calls[-1][0] == name and name != "self.add_vector":  # add_vector takes one vector
            calls[-1][1].append(ref)
        else:
            calls.append((name, [ref]))
    return calls


def _lts_add_calls(items: list[MobjectItem], roles: dict[str, str], names: dict[str, str]):
    """Add objects to a LinearTransformationScene and to the list that decides how it moves them."""
    return _runs(items, lambda m: "self.add_vector" if roles[m.id] == MOVING_VECTOR else _REGISTER[roles[m.id]],
                 names)


_FIXED_ADD = {FIXED_IN_FRAME: "self.add_fixed_in_frame_mobjects",
              FIXED_ORIENTATION: "self.add_fixed_orientation_mobjects"}


def add_calls(scene: Scene, names: dict[str, str]) -> list[tuple[str, list[Ref]]]:
    """The calls that put the objects shown at the start on screen: (method, the objects)."""
    tops = top_level(scene)
    shown = [m for m in tops if m.on_screen_at_start]
    if scene.kind == LINEAR:
        return _lts_add_calls(shown, _lts_roles(scene), names)
    if not scene_kind(scene).three_d:
        return [("self.add", [Ref(m.id, names[m.id]) for m in shown])] if shown else []
    calls = _runs(shown, lambda m: _FIXED_ADD.get(m.fixed, "self.add"), names)
    for fixed, method in _FIXED_ADD.items():
        later = [Ref(m.id, names[m.id]) for m in tops if not m.on_screen_at_start and m.fixed == fixed]
        if later:  # not on screen yet: the camera learns now that they are fixed, whenever they come in
            calls.append((method.replace("self.", "self.camera."), later))
    return calls


def _call_stmts(calls: list[tuple[str, list[Ref]]]) -> list[Do]:
    return [Do(_self_call(name, *refs), wrap=True) for name, refs in calls]


def _call_lines(calls, indent: str = INDENT) -> list[str]:
    return [line for s in _call_stmts(calls) for line in s.lines(indent)]


