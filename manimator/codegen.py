@dataclass
class SceneCode:
    """Everything construct() does, as statements: what both the printer and the scene plan read."""

    scene: Scene
    names: dict[str, str]
    setup: SceneSetup
    objects: list[MobCode]
    adds: list[Do]
    steps: list[StepCode]


def scene_code(scene: Scene, project: Project) -> SceneCode:
    codes, names = scene_objects(scene)
    walk = _Walk(scene, names)
    steps = [walk.step_code(i, step) for i, step in enumerate(scene.steps)]
    return SceneCode(scene, names, scene_setup(scene, project), codes, _call_stmts(add_calls(scene, names)), steps)


def scene_class_names(project: Project) -> dict[str, str]:
    return {s.id: s.name for s in project.scenes}


def scene_source(scene: Scene, project: Project, class_name: str | None = None) -> str:
    sc = scene_code(scene, project)
    out = class_lines(safe_identifier(class_name or scene.name), sc.setup)
    if sc.setup.statements:
        out.extend(INDENT + line for line in sc.setup.lines)
        out.append("")
    if sc.objects:
        out.append(f"{INDENT}# Objects")
        for c in sc.objects:
            if c.error:
                out.append(f"{INDENT}# Warning: {c.var}: {comment(c.error)}")
            out.extend(INDENT + line for line in c.lines())
        out.append("")
    out.extend(line for s in sc.adds for line in s.lines(INDENT))
    body = [line for st in sc.steps for s in st.statements for line in s.lines(INDENT)]
    if body:
        if out[-1]:
            out.append("")
        out.append(f"{INDENT}# Animation")
        out.extend(body)
    else:
        out.append(f"{INDENT}self.wait(1)  # no animation steps yet")
    return "\n".join(out) + "\n"


# The font Manimator draws text with (manimator/web/fonts/). Text, Paragraph and Table all make Text; MarkupText is
# a class of its own; Code names its font.
TEXT_FONT = "Crimson Pro"
_USES_TEXT = re.compile(r"\b(?:Text|Paragraph|Table)\(")
_USES_MARKUP = re.compile(r"\bMarkupText\(")


def uses_text(sources: list[str]) -> bool:
    """Whether the scenes make text in Manimator's font (Text, Paragraph, Table, MarkupText)."""
    return any(used.search(src) for src in sources for used in (_USES_TEXT, _USES_MARKUP))


def font_defaults(sources: list[str], bundled: bool = False) -> list[str]:
    """The set_default lines that give the scenes' text Manimator's font (none if they have no text). `bundled`: the
    font files come with the code (the zip download), so nothing needs installing."""
    classes = [name for name, used in (("Text", _USES_TEXT), ("MarkupText", _USES_MARKUP))
               if any(used.search(src) for src in sources)]
    if not classes:
        return []
    note = [] if bundled else [f"# Manimator draws text with {TEXT_FONT}, a free font (fonts.google.com). Without it "
                               "installed,", "# Manim uses its default font instead."]
    return [*note, *(f"{name}.set_default(font={py_str(TEXT_FONT)})" for name in classes)]


# The zip download (manimator/export.py) puts the fonts the text uses in fonts/ next to scene.py.
FONT_LOADER = """import pathlib

import manimpango
from manim import *

# The fonts Manimator draws text with, from the fonts folder next to this file: nothing to install.
for font_file in sorted((pathlib.Path(__file__).parent / "fonts").glob("*/*.ttf")):
    manimpango.register_font(str(font_file))
"""


def kit_imports(project: Project) -> list[str]:
    """The import of each package (server/kits.py) the project uses, from the zip's customizations folder."""
    lines = []
    for key in kit_types_in(project):
        spec = kit_spec(key)
        if spec is not None and spec.kit and not spec.blocked:
            lines.append(f"from customizations.{spec.kit['module']} import {spec.kit['class']}")
    return list(dict.fromkeys(lines))


def project_source(project: Project, file_name: str = "scene.py", bundled_fonts: bool = False) -> str:
    """The whole project as one Python file. `bundled_fonts`: for the zip download, which has the fonts with it."""
    first = safe_identifier(project.scenes[0].name) if project.scenes else "Scene1"
    scenes = [scene_source(scene, project) for scene in project.scenes]
    parts = [HEADER.format(file=file_name, scene=first), FONT_LOADER if bundled_fonts else "from manim import *\n"]
    imports = kit_imports(project)
    if imports:
        parts.append("# Custom objects and animations (the customizations folder)\n" + "\n".join(imports) + "\n")
    defaults = font_defaults(scenes, bundled_fonts)
    if defaults:
        parts.append("\n".join(defaults) + "\n")
    for source in scenes:
        parts.append("\n" + source)
    return "\n".join(parts)
