@dataclass
class SceneSetup:
    """How a scene class starts: what it inherits, its constructor arguments and the first lines of construct()."""

    base: str
    init_kwargs: list  # [(name, Node)]
    statements: list  # Do / Assign

    @property
    def init_args(self) -> list[str]:
        return [f"{k}={v.py()}" for k, v in self.init_kwargs]

    @property
    def lines(self) -> list[str]:  # without indentation
        return [line for s in self.statements for line in s.lines("")]

    @property
    def special_init(self) -> bool:
        return self.base == SPECIAL_THREE_D


def scene_setup(scene: Scene, project: Project) -> SceneSetup:
    kind = scene_kind(scene)

    def opt(name):
        return _option_value(scene, name)

    def node(name):
        return value_node(kind.option(name), opt(name), {})

    def changed(name):
        return opt(name) != kind.option(name).default

    kwargs: list = []
    stmts: list = []
    frame = "self.camera.frame"
    if kind.moving_camera:
        x, y = (float(v) for v in opt("camera_center")[:2])
        if x or y:
            stmts.append(Do(_self_call(f"{frame}.move_to", point_node([x, y]))))
        if float(opt("camera_zoom")) != 1:
            stmts.append(Do(_self_call(f"{frame}.set", width=_width(opt("camera_zoom")))))
        if any(a.anim == "camera_restore" for st in scene.steps for a in st.animations):
            stmts.append(Do(_self_call(f"{frame}.save_state")))  # for "Reset camera"
    if kind.three_d:
        angles = {k: float(opt(k)) for k in ("phi", "theta", "gamma", "zoom")}
        if scene.kind == SPECIAL_THREE_D and not any(changed(k) for k in angles):
            stmts.append(Do(_self_call("self.set_camera_to_default_position")))
        else:
            orient = {"phi": _degrees(angles["phi"]), "theta": _degrees(angles["theta"])}
            if angles["gamma"]:
                orient["gamma"] = _degrees(angles["gamma"])
            if angles["zoom"] != 1:
                orient["zoom"] = num_node(angles["zoom"])
            stmts.append(Do(_self_call("self.set_camera_orientation", **orient)))
    try:
        background = color_node(project.settings.background)
    except BAD_DATA:
        background = color_node("#000000")
    if background.code != "BLACK":
        stmts.append(Assign("self.camera.background_color", background))
        if scene.kind == ZOOMED:  # the zoomed display has a camera of its own
            stmts.append(Assign("self.zoomed_camera.background_color", background))
    if scene.kind == ZOOMED:
        for name in ("zoom_factor", "zoomed_display_width", "zoomed_display_height", "zoomed_display_corner",
                     "zoomed_camera_frame_starting_position"):
            if changed(name):
                kwargs.append((name, node(name)))
        if changed("lens_color"):
            stmts.append(Do(_self_call("self.zoomed_camera.frame.set_color", node("lens_color"))))
        if changed("display_color"):
            stmts.append(Do(_self_call("self.zoomed_display.display_frame.set_color", node("display_color"))))
        if opt("zoom_at_start"):
            stmts.append(Do(_self_call("self.activate_zooming")))
    elif scene.kind == VECTOR_SCENE:
        background = opt("background")
        if background == "plane":
            stmts.append(Do(_self_call("self.add_plane")))
        elif background == "axes":
            stmts.append(Do(_self_call("self.add_axes")))
        if opt("basis_vectors"):
            stmts.append(Do(_self_call("self.add", _self_call("self.get_basis_vectors"))))
        if opt("basis_vector_labels"):
            stmts.append(Do(_self_call("self.add", _self_call("self.get_basis_vector_labels"))))
        if changed("basis_vector_stroke_width"):
            kwargs.append(("basis_vector_stroke_width", node("basis_vector_stroke_width")))
    elif scene.kind == LINEAR:
        for name in ("include_background_plane", "show_coordinates", "include_foreground_plane",
                     "show_basis_vectors", "i_hat_color", "j_hat_color", "basis_vector_stroke_width",
                     "leave_ghost_vectors"):
            if changed(name):
                kwargs.append((name, node(name)))
        if opt("unit_square"):
            color = {"color": node("unit_square_color")} if changed("unit_square_color") else {}
            stmts.append(Do(_self_call("self.add_unit_square", **color)))
    return SceneSetup(kind.key, kwargs, stmts)


_SPECIAL_INIT = [
    "# SpecialThreeDScene.__init__ uses self.renderer before Scene.__init__ creates it, so in recent",
    "# Manim versions it stops with an AttributeError once its own settings are stored. Finish as a",
    "# ThreeDScene, which is what it would do next.",
    "try:",
    "    super().__init__(**kwargs)",
    "except AttributeError:",
    "    ThreeDScene.__init__(self, **kwargs)",
]


def class_lines(name: str, setup: SceneSetup) -> list[str]:
    """`class Name(Base):`, an __init__ if the scene needs one, and the construct() line."""
    out = [f"class {name}({setup.base}):"]
    if setup.special_init:
        out += ["    def __init__(self, **kwargs):", *("        " + line for line in _SPECIAL_INIT), ""]
    elif setup.init_kwargs:
        out += ["    def __init__(self, **kwargs):",
                *join_call("super().__init__", [*setup.init_args, "**kwargs"], "        "), ""]
    out.append("    def construct(self):")
    return out


