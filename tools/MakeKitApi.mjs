// Writes manimator/web/js/engine/KitApi.js: the "manimator" module a customization's kit.js imports (server/kits.py).
// It names what Manim's `from manim import *` gives a scene, as the browser engine has it: every object and
// animation class, the constants and directions, the named colors (as hex), the rate functions, plus the vector
// helpers JavaScript needs where Python writes RIGHT * 2. Run it again when the engine gains classes:
//     node tools/MakeKitApi.mjs          (tests/js/kits.test.mjs checks the file is current)

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const engine = new URL("../manimator/web/js/engine/", import.meta.url);
const { CLASSES } = await import(new URL("plan/names.js", engine));
const { ANIMATIONS } = await import(new URL("anim/index.js", engine));
const frozen = await import(new URL("manim/frozen.js", engine));
const rates = await import(new URL("core/rates.js", engine));
const { RATE_FUNCTIONS } = rates;

const MATH = ["add", "sub", "mul", "mulv", "neg", "dot", "cross", "norm", "normalize", "midpoint", "rotateVector",
  "angleOfVector", "angleBetweenVectors", "interpolatePoint", "linspace", "arange", "clip", "sign"];
const COLOR = ["ManimColor", "color", "interpolateColor", "colorGradient", "averageColor", "invertColor"];

export function kitApiSource() {
  const taken = new Set();
  const take = (names) => names.filter((n) => !taken.has(n) && taken.add(n)).sort();
  const classes = take(Object.keys(CLASSES));
  const animations = take(Object.keys(ANIMATIONS));
  const constants = take(Object.keys(frozen).filter((n) => n !== "COLOR_TABLE" && /^[A-Z][A-Z0-9_]*$/.test(n)));
  const colors = take(Object.keys(frozen.COLOR_TABLE).filter((n) => /^[A-Z][A-Z0-9_]*$/.test(n)));
  const rateNames = take(Object.keys(RATE_FUNCTIONS).filter((n) => n in rates));
  const math = take(MATH);
  const color = take(COLOR);
  const wrap = (items, indent = "  ") => {
    const lines = [];
    let line = indent;
    for (const item of items) {
      if (line.length + item.length + 2 > 118) {
        lines.push(line.trimEnd());
        line = indent;
      }
      line += `${item}, `;
    }
    lines.push(line.trimEnd());
    return lines.join("\n");
  };
  return `// "manimator": what a customization's kit.js imports (see server/kits.py and /docs/customizations). Generated by
// tools/MakeKitApi.mjs from the engine's own tables; don't edit it, run the tool again.
//
// The same names Manim's \`from manim import *\` gives a scene, as the browser engine has them: object and animation
// classes (made like Python's, \`Circle.make({ radius: 2 })\`), constants and directions, colors as hex strings, rate
// functions, and vector helpers for what Python writes with operators (\`mul(RIGHT, 2)\` for RIGHT * 2).

import { ANIMATIONS } from "./anim/index.js";
import { ManimColor } from "./core/color.js";
import { CLASSES } from "./plan/names.js";

export const {
${wrap(classes)}
} = CLASSES;

export const {
${wrap(animations)}
} = ANIMATIONS;

export {
${wrap(constants)}
} from "./manim/frozen.js";

export {
${wrap(rateNames)}
} from "./core/rates.js";

export {
${wrap(math)}
} from "./core/math.js";

export {
${wrap(color)}
} from "./core/color.js";

const hex = (name) => new ManimColor(name).to_hex();
${colors.map((c) => `export const ${c} = hex("${c}");`).join("\n")}
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = new URL("KitApi.js", engine);
  writeFileSync(target, kitApiSource());
  console.log(`wrote ${fileURLToPath(target)}`);
}
